"""Y09 (W24, R8): O14 -- the key-independent constant sums of the F_p
full-block structure at the exact-boundary cells D = T.

Three parts, all driven by the repository's own cipher objects:

  dec   YuX decryption.  p = 5 (layer 3) and p = 17
        (layer 4): 3 REAL master keys through `key_schedule` x 2 sets of
        inactive constants, full-block structure on block 0, compared word by
        word with the top-form recursion of tools/topform_constants.py.
        p = 257 (layer 6) by the recursion only (the 2^32 direct sum is the C
        kernel `tools/topform_kernels direct 257 6 <seed> linv_257.txt`).

  enc   The chosen-plaintext direction (W24 step 3).  The exact-boundary
        condition is 8^{l-1} = 4(p-1), whose only prime solutions are
        p = 3 / layer 2, p = 17 / layer 3 and p = 65537 / layer 7.  DuX's two
        circulants are singular mod 17 and YuX's is singular mod 3, so the two
        halves are run at the only primes where the real cipher exists:
        YuX at p = 17 layer 3, DuX at p = 3 layer 2 (with O2's fixed-L0 keys).

  rank  The mechanism behind what `enc` measures.  The top form of an S-box
        output only involves SOME of the four block inputs: YuX decryption
        uses offsets (1,2,3), YuX encryption (0,1), DuX encryption (0,3).  If
        the rows of the layer matrix that those offsets select span fewer than
        four dimensions on the free variables (y0..y3), every top form at
        every layer >= 2 lies in a subring generated by < 4 linear forms, the
        fibres of y |-> (those forms) have size divisible by p, and the sum
        over F_p^4 is 0 -- so the exact-boundary cell is an ordinary zero-sum
        and not a non-zero constant.

Usage
  python experiments/Y09_topform_constants/run.py --part all --out results/Y09_topform_constants
"""
from __future__ import annotations

import argparse
import itertools
import json
import os
import sys
import time

import numpy as np

_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
for _p in (_ROOT, os.path.join(_ROOT, "tools")):
    if _p not in sys.path:
        sys.path.insert(0, _p)

from dux.registry import get_cipher                                  # noqa: E402
from dux.linear import rotl, t_xor                                   # noqa: E402
from topform_constants import (SBOX_TOP, TOP_POSITION, constants_affine,   # noqa: E402
                               constants_projective, direct_sums_general,
                               exact_hit_layer, instance_for, layer_matrix,
                               linv_matrix)

WORDS = 16
SEEDS = (2026, 7, 11)          # the repository's three master-key seeds
CONSTANT_SETS = 2


# ---------------------------------------------------------------------------
def predicted(p, layers, cipher, direction, affine=False):
    """The top-form prediction for all 16 words: 0 below T, the recursion's
    constant at an exact hit, None where D > T (no prediction)."""
    key = (cipher, direction)
    M = linv_matrix(p) if key == ("yux", "dec") else layer_matrix(p, cipher, direction)
    top_fn = SBOX_TOP[key]
    c, deg = constants_projective(p, layers, M, top_fn)
    T = 4 * (p - 1)
    c = [0 if deg[i] < T else (c[i] if deg[i] % (p - 1) == 0 else None) for i in range(WORDS)]
    out = {"predicted": c, "formal_degree": deg, "T": T}
    if affine:
        ca, _ = constants_affine(p, layers, M, top_fn)
        out["predicted_affine"] = [0 if deg[i] < T else (ca[i] if deg[i] % (p - 1) == 0 else None)
                                   for i in range(WORDS)]
        out["affine_matches_projective"] = out["predicted_affine"] == c
    return out


def real_key_rows(p, layers, cipher, direction):
    """3 real master keys x 2 inactive-constant sets of full-block sums."""
    rows = []
    for s in SEEDS:
        rows += direct_sums_general(p, layers, seed=s, cipher=cipher, direction=direction,
                                    constant_sets=CONSTANT_SETS)
    return rows


def cell(p, layers, cipher, direction, affine=True):
    t0 = time.time()
    out = {"p": p, "layers": layers, "cipher": cipher, "direction": direction,
           "instance": instance_for(p, cipher),
           "top_position": TOP_POSITION[(cipher, direction)],
           "exact_hit_layer": exact_hit_layer(p, direction, cipher)}
    out.update(predicted(p, layers, cipher, direction, affine=affine))
    rows = real_key_rows(p, layers, cipher, direction)
    for r in rows:
        r["matches"] = r["sums"] == out["predicted"]
    out["real_keys"] = rows
    out["all_match"] = all(r["matches"] for r in rows)
    out["key_independent"] = len({tuple(r["sums"]) for r in rows}) == 1
    out["seconds"] = round(time.time() - t0, 1)
    print(f"[{cipher}/{direction}] p={p} layer {layers}: T={out['T']} "
          f"D={out['formal_degree']}")
    print(f"    recursion : {out['predicted']}")
    for r in rows:
        print(f"    key {r['seed']:>4} cst {r['constant_set']}: {r['sums']}  match={r['matches']}")
    print(f"    all_match={out['all_match']}  key_independent={out['key_independent']}  "
          f"({out['seconds']} s)")
    return out


# ---------------------------------------------------------------------------
def rank_table():
    """Which inputs each S-box top form uses, and the rank of the rows they
    select on (y0..y3).  Rank < 4 => the exact-boundary sum is 0."""
    uses = {("yux", "dec"): (1, 2, 3), ("yux", "enc"): (0, 1), ("dux", "enc"): (0, 3)}
    out = []
    for (cipher, direction), offs in uses.items():
        for p in (3, 5, 17, 257, 65537):
            if instance_for(p, cipher) is None:
                continue
            try:
                M = linv_matrix(p) if (cipher, direction) == ("yux", "dec") \
                    else layer_matrix(p, cipher, direction)
            except SystemExit:
                continue
            rows = [[int(M[4 * b + o][j]) % p for j in range(4)] for b in range(4) for o in offs]
            r = _rank_mod_p(rows, p)
            out.append({"cipher": cipher, "direction": direction, "offsets": list(offs),
                        "p": p, "rows": len(rows), "rank": r, "sum_is_zero_for_all_layers": r < 4})
            print(f"  {cipher}/{direction} p={p:6d}: offsets {offs}, rank {r}/4 "
                  f"-> {'sum = 0 at every layer' if r < 4 else 'no degeneracy'}")
    return out


def _rank_mod_p(rows, p):
    A = [r[:] for r in rows]
    r = 0
    for c in range(4):
        piv = next((i for i in range(r, len(A)) if A[i][c] % p), None)
        if piv is None:
            continue
        A[r], A[piv] = A[piv], A[r]
        inv = pow(A[r][c], p - 2, p)
        A[r] = [(v * inv) % p for v in A[r]]
        for i in range(len(A)):
            if i != r and A[i][c] % p:
                f = A[i][c]
                A[i] = [(A[i][k] - f * A[r][k]) % p for k in range(4)]
        r += 1
    return r


def rank_exact_over_Q():
    """The YuX encryption degeneracy, exactly over Q from params.V_P_FRACTIONS
    (so it is not an accident of one prime)."""
    from fractions import Fraction as Fr
    from yux.params import V_P_FRACTIONS
    v = [Fr(a, b) for a, b in V_P_FRACTIONS]
    rows = {i: [v[(j - i) % WORDS] for j in range(4)] for i in range(WORDS)}
    used = [4 * b + o for b in range(4) for o in (0, 1)]
    R = [rows[i] for i in used]
    rk, _ = _rref_Q(R)
    decomp = {i: {"y0": str(rows[i][0] - rows[i][2]), "y1": str(rows[i][1] - rows[i][2]),
                  "sigma": str(rows[i][2]),
                  "y2_eq_y3": rows[i][2] == rows[i][3]} for i in used}
    print(f"  YuX encryption rows {used}: exact rank over Q = {rk} "
          f"(all of the form a.y0 + b.y1 + c.sigma)")
    return {"rows_used": used, "rank_over_Q": rk, "decomposition": decomp}


def _rref_Q(R):
    A = [r[:] for r in R]
    r = 0
    for c in range(4):
        piv = next((i for i in range(r, len(A)) if A[i][c] != 0), None)
        if piv is None:
            continue
        A[r], A[piv] = A[piv], A[r]
        A[r] = [x / A[r][c] for x in A[r]]
        for i in range(len(A)):
            if i != r and A[i][c] != 0:
                f = A[i][c]
                A[i] = [A[i][k] - f * A[r][k] for k in range(4)]
        r += 1
    return r, A


