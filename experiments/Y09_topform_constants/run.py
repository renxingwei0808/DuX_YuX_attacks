def o2_rotation_check(p=3, layers=3, seed=2026):
    """DuX only: the real `encrypt_layers` uses the key-dependent L0/L1, the
    analysis uses O2's fixed-L0 cipher.  The 16 sums must agree up to the word
    rotation Rot_{4 T_k}; this reports the exponent that matches.

    Run PAST the exact-boundary layer on purpose (default layer 3 at p = 3,
    where D = 64 > T = 8): at the boundary layer every sum is 0, so a rotation
    test there is vacuous."""
    c = get_cipher(instance_for(p, "dux"))
    rng = np.random.default_rng(seed)
    K = c.random_key(rng)
    rks = c.key_schedule(K)
    rks_fixed, _T = c.equivalent_fixedL0_keys(rks)
    cst = [int(v) for v in rng.integers(0, p, size=WORDS)]
    grid = np.array(list(itertools.product(range(p), repeat=4)), dtype=np.int64)
    n = grid.shape[0]
    x = [np.full(n, int(v) % p, dtype=np.int64) for v in cst]
    for i in range(4):
        x[i] = grid[:, i].copy()
    x = tuple(x)
    real = c.encrypt_layers(x, rks, layers, rounds=c.r, vec=True)
    real = [int(np.asarray(z, dtype=np.int64).sum() % p) for z in real]
    y = c.ARK(x, rks_fixed[0], True)
    y = c.SL(y, True)
    for k in range(1, layers):
        y = c.lin.L(y, 0, True)
        y = c.ARK(y, rks_fixed[k], True)
        y = c.SL(y, True)
    fixed = [int(np.asarray(z, dtype=np.int64).sum() % p) for z in y]
    Tk = sum(t_xor(rks[i]) for i in range(1, layers))
    match = [j for j in range(WORDS) if list(rotl(tuple(fixed), j)) == real]
    print(f"  DuX p={p} layer {layers}: real encrypt_layers sums {real}")
    print(f"                    fixed-L0 sums {fixed}")
    print(f"    accumulated t_xor T_{layers - 1} = {Tk} -> predicted rotation 4T = {4 * Tk % WORDS}; "
          f"rotations that match: {match}")
    return {"p": p, "layers": layers, "seed": seed, "real": real, "fixed_L0": fixed,
            "T": Tk, "predicted_rotation": 4 * Tk % WORDS, "matching_rotations": match}


# ---------------------------------------------------------------------------
def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--part", choices=("dec", "enc", "rank", "all"), default="all")
    ap.add_argument("--out", default=None, help="directory for the JSON artefacts")
    a = ap.parse_args(argv)
    res = {"seeds": list(SEEDS), "constant_sets": CONSTANT_SETS}

    if a.part in ("dec", "all"):
        print("=== O14, decryption direction (YuX) ===")
        res["dec"] = [cell(5, 3, "yux", "dec"), cell(17, 4, "yux", "dec")]
        print("--- p = 257, layer 6: recursion only (the 2^32 sum is the C kernel) ---")
        res["dec_257"] = predicted(257, 6, "yux", "dec")
        print("    recursion :", res["dec_257"]["predicted"])

    if a.part in ("enc", "all"):
        print("\n=== O14, encryption direction (CPA) ===")
        res["enc"] = [cell(17, 3, "yux", "enc"), cell(3, 2, "dux", "enc")]
        print("--- O2 cross-check (DuX has a key-dependent linear layer) ---")
        res["o2_rotation"] = [o2_rotation_check(seed=s) for s in SEEDS]

    if a.part in ("rank", "all"):
        print("\n=== mechanism: the rank of the rows the top forms select ===")
        res["rank"] = rank_table()
        res["rank_over_Q"] = rank_exact_over_Q()

    if a.out:
        os.makedirs(a.out, exist_ok=True)
        path = os.path.join(a.out, f"y09_{a.part}.json")
        with open(path, "w") as fh:
            json.dump(res, fh, indent=1)
        print(f"\nwrote {path}")
    return res


if __name__ == "__main__":
    main()
